//! Dev tool: round-trips the translation catalogs under `po/` from the source.
//!
//!   cargo run --bin gen-po
//!
//! It gathers every translatable message from two places:
//!
//! - the `t!("..")` and `tn!("..", "..", n)` call sites in `src/**/*.rs`, and
//! - the authored `message` of every control in `help.toml`, carried across with
//!   the control's help-id as its `msgctxt` so a translator can see which
//!   control a paragraph of prose belongs to.
//!
//! then merges them into `po/pubsplash.pot` (the template, every `msgstr`
//! empty) and into each `po/<lang>.po` beside it:
//!
//! - new messages are appended with an empty `msgstr`, which the runtime reads
//!   as "not translated" and falls back to the English for,
//! - existing messages keep their translation, and only the `#:` source
//!   references are refreshed,
//! - messages that have left the source are written back as commented-out `#~`
//!   entries rather than deleted, so rewording an English string never throws
//!   away the Spanish that went with it.
//!
//! Entries are sorted by context and msgid for stable diffs, exactly as
//! `gen-help` sorts `help.toml`.
//!
//! The `.po` reader and the string escaper come from `src/i18n.rs` itself,
//! `#[path]`-included below rather than reimplemented — the same trick
//! `soundpack.rs` uses for `audio/convert.rs`, and for the same reason: a writer
//! and a reader that disagree about escaping would corrupt translated text in a
//! way that only shows up on a user's machine.

// Only the `.po` reader and the escaper are wanted here; the runtime half of the
// module (catalog lookup, plural evaluation, the Win32 language probe) comes
// along with the file and is deliberately unused.
#[allow(dead_code)]
#[path = "../i18n.rs"]
mod i18n;

use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

use i18n::{PoEntry, po_escape};

/// Wrapped into the template so a translator opening it knows the rules.
const POT_HEADER: &str = "\
# Pubsplash interface translations.
#
# This file is generated by the `gen-po` dev tool:
#   cargo run --bin gen-po
# It rescans the source for `t!`/`tn!` calls and `help.toml` for context-help
# prose, adds anything new with an empty translation, and preserves every
# translation already written. Messages that have left the source are kept as
# commented-out `#~` entries rather than deleted.
#
# The msgid IS the English text the app would otherwise show, so an empty
# msgstr is not a bug: it simply leaves that string in English. Translate at
# your own pace and nothing breaks.
#
# `{name}` placeholders are substituted at runtime. Keep every placeholder that
# appears in the msgid, spelled exactly the same -- but you are free to move
# them, which is the whole reason they are named rather than positional.
#
# A `msgctxt` line is the help-id of the control a message belongs to.
";

/// A message found in the source or in `help.toml`.
#[derive(Clone, Default)]
struct Message {
    ctxt: Option<String>,
    id: String,
    id_plural: Option<String>,
    /// `file:line` references, for the translator's `#:` comments.
    refs: Vec<String>,
    /// A note about where the message comes from, written as a `#.` comment.
    note: Option<String>,
}

fn main() {
    let root = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let src_dir = root.join("src");
    let po_dir = root.join("po");

    let mut messages: BTreeMap<(Option<String>, String), Message> = BTreeMap::new();

    let mut call_sites = 0usize;
    for file in rust_files(&src_dir) {
        let Ok(text) = fs::read_to_string(&file) else {
            continue;
        };
        let relative = file
            .strip_prefix(&root)
            .unwrap_or(&file)
            .to_string_lossy()
            .replace('\\', "/");
        for found in scan_calls(&text) {
            call_sites += 1;
            let entry = messages
                .entry((None, found.singular.clone()))
                .or_insert_with(|| Message {
                    ctxt: None,
                    id: found.singular.clone(),
                    id_plural: found.plural.clone(),
                    ..Message::default()
                });
            // A message used both with and without a plural keeps the plural:
            // dropping it would lose the second form for the translator.
            if entry.id_plural.is_none() {
                entry.id_plural = found.plural.clone();
            }
            entry.refs.push(format!("{relative}:{}", found.line));
        }
    }
    println!("Found {call_sites} t!/tn! call sites.");

    let help_added = collect_help(&root, &mut messages);
    println!("Found {help_added} context-help messages in help.toml.");
    println!("{} distinct messages in total.", messages.len());

    fs::create_dir_all(&po_dir).expect("could not create po/");

    // The template first: it is what a new language is copied from.
    write_catalog(
        &po_dir.join("pubsplash.pot"),
        &messages,
        "en",
        "nplurals=2; plural=(n != 1);",
        true,
    );

    // Then every existing catalog, translations preserved.
    let mut catalogs: Vec<PathBuf> = fs::read_dir(&po_dir)
        .into_iter()
        .flatten()
        .flatten()
        .map(|e| e.path())
        .filter(|p| p.extension().is_some_and(|e| e == "po"))
        .collect();
    catalogs.sort();
    for path in catalogs {
        let lang = path
            .file_stem()
            .map(|s| s.to_string_lossy().to_string())
            .unwrap_or_default();
        let plural_forms = existing_plural_forms(&path)
            .unwrap_or_else(|| "nplurals=2; plural=(n != 1);".to_string());
        write_catalog(&path, &messages, &lang, &plural_forms, false);
    }
}

// --- gathering -------------------------------------------------------------

fn rust_files(dir: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let Ok(entries) = fs::read_dir(dir) else {
        return out;
    };
    let mut entries: Vec<PathBuf> = entries.flatten().map(|e| e.path()).collect();
    entries.sort();
    for path in entries {
        if path.is_dir() {
            out.extend(rust_files(&path));
        } else if path.extension().is_some_and(|e| e == "rs") {
            out.push(path);
        }
    }
    out
}

/// A `t!`/`tn!` call found by [`scan_calls`].
struct Call {
    singular: String,
    plural: Option<String>,
    line: usize,
}

/// Walks the source for `t!(` and `tn!(` outside comments and string literals,
/// and reads the literal arguments.
///
/// A hand-rolled scan rather than a regex because the arguments are real Rust
/// string literals: they carry escapes, and long ones are routinely broken
/// across lines with a trailing `\`, which the compiler joins and so must we.
/// A call whose first argument is not a literal is reported and skipped — the
/// macro rejects it anyway, but saying so here is what turns a silently
/// untranslated string into a message on the console.
fn scan_calls(source: &str) -> Vec<Call> {
    let chars: Vec<char> = source.chars().collect();
    let mut out = Vec::new();
    let mut i = 0;
    let mut line = 1usize;

    while i < chars.len() {
        let c = chars[i];
        if c == '\n' {
            line += 1;
            i += 1;
            continue;
        }
        // Comments.
        if c == '/' && chars.get(i + 1) == Some(&'/') {
            while i < chars.len() && chars[i] != '\n' {
                i += 1;
            }
            continue;
        }
        if c == '/' && chars.get(i + 1) == Some(&'*') {
            let mut depth = 1;
            i += 2;
            while i < chars.len() && depth > 0 {
                if chars[i] == '\n' {
                    line += 1;
                }
                if chars[i] == '/' && chars.get(i + 1) == Some(&'*') {
                    depth += 1;
                    i += 2;
                } else if chars[i] == '*' && chars.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    i += 2;
                } else {
                    i += 1;
                }
            }
            continue;
        }
        // Raw strings, which the scanner must step over whole.
        if c == 'r'
            && !is_ident(chars.get(i.wrapping_sub(1)).copied())
            && let Some(end) = skip_raw_string(&chars, i, &mut line)
        {
            i = end;
            continue;
        }
        // Ordinary string and char literals: skipped so a `t!(` written inside
        // one (this file's own doc comments, for instance) is not extracted.
        if c == '"' {
            let mut j = i + 1;
            while j < chars.len() {
                if chars[j] == '\\' {
                    j += 2;
                    continue;
                }
                if chars[j] == '\n' {
                    line += 1;
                }
                if chars[j] == '"' {
                    break;
                }
                j += 1;
            }
            i = j + 1;
            continue;
        }
        if c == '\'' && chars.get(i + 1).is_some_and(|c| *c != '\'') {
            // A char literal or a lifetime; both are safe to step past one char.
            i += 1;
            continue;
        }

        // The macro calls themselves.
        let plural = chars.get(i) == Some(&'t')
            && chars.get(i + 1) == Some(&'n')
            && chars.get(i + 2) == Some(&'!');
        let singular = chars.get(i) == Some(&'t') && chars.get(i + 1) == Some(&'!');
        if (plural || singular) && !is_ident(chars.get(i.wrapping_sub(1)).copied()) {
            let after_bang = if plural { i + 3 } else { i + 2 };
            let mut j = after_bang;
            while j < chars.len() && chars[j].is_whitespace() {
                if chars[j] == '\n' {
                    line += 1;
                }
                j += 1;
            }
            if chars.get(j) == Some(&'(') {
                let call_line = line;
                let mut k = j + 1;
                match read_literal(&chars, &mut k, &mut line) {
                    Some(first) => {
                        let second = if plural {
                            skip_comma(&chars, &mut k, &mut line);
                            read_literal(&chars, &mut k, &mut line)
                        } else {
                            None
                        };
                        if plural && second.is_none() {
                            eprintln!(
                                "warning: line {call_line}: tn! without two literal forms; skipped"
                            );
                        } else {
                            out.push(Call {
                                singular: first,
                                plural: second,
                                line: call_line,
                            });
                        }
                    }
                    None => {
                        eprintln!(
                            "warning: line {call_line}: {}! argument is not a string literal, so it \
                             cannot be translated",
                            if plural { "tn" } else { "t" }
                        );
                    }
                }
                i = k;
                continue;
            }
        }
        i += 1;
    }
    out
}

fn is_ident(c: Option<char>) -> bool {
    c.is_some_and(|c| c.is_alphanumeric() || c == '_')
}

/// Steps past a raw string starting at `i`, returning the index after it.
fn skip_raw_string(chars: &[char], i: usize, line: &mut usize) -> Option<usize> {
    let mut j = i + 1;
    let mut hashes = 0;
    while chars.get(j) == Some(&'#') {
        hashes += 1;
        j += 1;
    }
    if chars.get(j) != Some(&'"') {
        return None;
    }
    j += 1;
    let closing: String = std::iter::once('"')
        .chain(std::iter::repeat_n('#', hashes))
        .collect();
    let closing: Vec<char> = closing.chars().collect();
    while j < chars.len() {
        if chars[j] == '\n' {
            *line += 1;
        }
        if chars[j..].starts_with(&closing[..]) {
            return Some(j + closing.len());
        }
        j += 1;
    }
    Some(chars.len())
}

/// Reads the next Rust string literal, leaving `i` just past it.
///
/// Handles the escapes that actually occur in our strings, and in particular
/// the `\` at end of line that the compiler swallows along with the following
/// indentation — every long message in the UI is written that way, and a
/// scanner that kept the newline would produce a msgid the runtime could never
/// match.
fn read_literal(chars: &[char], i: &mut usize, line: &mut usize) -> Option<String> {
    while *i < chars.len() && chars[*i].is_whitespace() {
        if chars[*i] == '\n' {
            *line += 1;
        }
        *i += 1;
    }
    if chars.get(*i) != Some(&'"') {
        return None;
    }
    *i += 1;
    let mut out = String::new();
    while *i < chars.len() {
        let c = chars[*i];
        if c == '"' {
            *i += 1;
            return Some(out);
        }
        if c == '\n' {
            *line += 1;
        }
        if c != '\\' {
            out.push(c);
            *i += 1;
            continue;
        }
        *i += 1;
        match chars.get(*i) {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('0') => out.push('\0'),
            Some('\\') => out.push('\\'),
            Some('"') => out.push('"'),
            Some('\'') => out.push('\''),
            // Line continuation: the newline and the indentation that follows
            // it are not part of the string. `\r\n` counts, and has to: these
            // sources are CRLF, rustc normalises the line ending before it
            // lexes, and a scanner that did not would put a carriage return and
            // a run of indentation inside the msgid — which is then a msgid the
            // running program can never produce, so the translation of every
            // wrapped message would silently never apply.
            Some('\r') | Some('\n') => {
                if chars.get(*i) == Some(&'\r') && chars.get(*i + 1) == Some(&'\n') {
                    *i += 1;
                }
                *line += 1;
                *i += 1;
                while *i < chars.len() && (chars[*i] == ' ' || chars[*i] == '\t') {
                    *i += 1;
                }
                continue;
            }
            Some('u') => {
                // `\u{1F600}`.
                *i += 1;
                if chars.get(*i) == Some(&'{') {
                    let mut hex = String::new();
                    *i += 1;
                    while *i < chars.len() && chars[*i] != '}' {
                        hex.push(chars[*i]);
                        *i += 1;
                    }
                    if let Ok(code) = u32::from_str_radix(&hex, 16)
                        && let Some(c) = char::from_u32(code)
                    {
                        out.push(c);
                    }
                }
                *i += 1;
                continue;
            }
            Some(other) => out.push(*other),
            None => return None,
        }
        *i += 1;
    }
    None
}

fn skip_comma(chars: &[char], i: &mut usize, line: &mut usize) {
    while *i < chars.len() {
        match chars[*i] {
            ',' => {
                *i += 1;
                return;
            }
            '\n' => {
                *line += 1;
                *i += 1;
            }
            c if c.is_whitespace() => *i += 1,
            _ => return,
        }
    }
}

/// Adds every authored context-help message, keyed by the control's help-id.
fn collect_help(root: &Path, into: &mut BTreeMap<(Option<String>, String), Message>) -> usize {
    #[derive(serde::Deserialize, Default)]
    struct HelpFile {
        #[serde(default)]
        control: Vec<HelpEntry>,
    }
    #[derive(serde::Deserialize)]
    struct HelpEntry {
        id: String,
        #[serde(default)]
        label: String,
        #[serde(default)]
        message: String,
    }

    let path = root.join("help.toml");
    let Ok(text) = fs::read_to_string(&path) else {
        eprintln!("warning: help.toml not found; context help will not be translatable");
        return 0;
    };
    let parsed: HelpFile = match toml::from_str(&text) {
        Ok(p) => p,
        Err(e) => {
            eprintln!("warning: could not parse help.toml ({e}); skipping context help");
            return 0;
        }
    };
    let mut count = 0;
    for entry in parsed.control {
        if entry.message.trim().is_empty() {
            continue;
        }
        count += 1;
        into.entry((Some(entry.id.clone()), entry.message.clone()))
            .or_insert_with(|| Message {
                ctxt: Some(entry.id.clone()),
                id: entry.message.clone(),
                id_plural: None,
                refs: vec!["help.toml".to_string()],
                note: Some(format!("Context help for the {}.", entry.label)),
            });
    }
    count
}

// --- writing ---------------------------------------------------------------

/// Reads the `Plural-Forms:` header out of an existing catalog so rewriting it
/// never silently resets a language's plural rule to English's.
fn existing_plural_forms(path: &Path) -> Option<String> {
    let text = fs::read_to_string(path).ok()?;
    let header = i18n::parse_po(&text)
        .into_iter()
        .find(|e| e.id.is_empty())?;
    header
        .msgstrs
        .first()?
        .lines()
        .find_map(|l| l.trim().strip_prefix("Plural-Forms:"))
        .map(|v| v.trim().to_string())
}

fn write_catalog(
    path: &Path,
    messages: &BTreeMap<(Option<String>, String), Message>,
    lang: &str,
    plural_forms: &str,
    is_template: bool,
) {
    // What the file already says, so translations survive the rewrite.
    let previous: Vec<PoEntry> = fs::read_to_string(path)
        .map(|text| i18n::parse_po(&text))
        .unwrap_or_default();
    let mut existing: BTreeMap<(Option<String>, String), Vec<String>> = BTreeMap::new();
    for entry in previous {
        if entry.id.is_empty() || entry.msgstrs.iter().all(|s| s.is_empty()) {
            continue;
        }
        existing.insert((entry.ctxt, entry.id), entry.msgstrs);
    }

    let nplurals = plural_forms
        .split(';')
        .find_map(|p| p.trim().strip_prefix("nplurals="))
        .and_then(|v| v.trim().parse::<usize>().ok())
        .unwrap_or(2)
        .max(1);

    let mut out = String::with_capacity(256 * 1024);
    out.push_str(POT_HEADER);
    out.push_str("msgid \"\"\nmsgstr \"\"\n");
    out.push_str("\"Project-Id-Version: pubsplash\\n\"\n");
    out.push_str("\"MIME-Version: 1.0\\n\"\n");
    out.push_str("\"Content-Type: text/plain; charset=UTF-8\\n\"\n");
    out.push_str("\"Content-Transfer-Encoding: 8bit\\n\"\n");
    out.push_str(&format!("\"Language: {lang}\\n\"\n"));
    out.push_str(&format!("\"Plural-Forms: {plural_forms}\\n\"\n"));
    out.push('\n');

    let mut translated = 0usize;
    for (key, message) in messages {
        if let Some(note) = &message.note {
            out.push_str(&format!("#. {note}\n"));
        }
        for reference in &message.refs {
            out.push_str(&format!("#: {reference}\n"));
        }
        if let Some(ctxt) = &message.ctxt {
            out.push_str(&format!("msgctxt {}\n", quoted(ctxt)));
        }
        out.push_str(&format!("msgid {}\n", quoted(&message.id)));

        let current = if is_template {
            None
        } else {
            existing.remove(key)
        };
        if current.is_some() {
            translated += 1;
        }
        match &message.id_plural {
            Some(plural) => {
                out.push_str(&format!("msgid_plural {}\n", quoted(plural)));
                for index in 0..nplurals {
                    let text = current
                        .as_ref()
                        .and_then(|forms| forms.get(index))
                        .map(String::as_str)
                        .unwrap_or("");
                    out.push_str(&format!("msgstr[{index}] {}\n", quoted(text)));
                }
            }
            None => {
                let text = current
                    .as_ref()
                    .and_then(|forms| forms.first())
                    .map(String::as_str)
                    .unwrap_or("");
                out.push_str(&format!("msgstr {}\n", quoted(text)));
            }
        }
        out.push('\n');
    }

    // Whatever is left in `existing` has gone from the source. Keep it, commented
    // out: an English string being reworded is the common case, and the old
    // translation is the fastest way to write the new one.
    if !existing.is_empty() {
        out.push_str(
            "# Messages below are no longer in the source. They are kept so a reworded\n\
             # English string does not throw away the translation that went with it.\n\n",
        );
        for ((ctxt, id), forms) in &existing {
            if let Some(ctxt) = ctxt {
                out.push_str(&format!("#~ msgctxt {}\n", quoted(ctxt)));
            }
            out.push_str(&format!("#~ msgid {}\n", quoted(id)));
            for (index, form) in forms.iter().enumerate() {
                if forms.len() == 1 {
                    out.push_str(&format!("#~ msgstr {}\n", quoted(form)));
                } else {
                    out.push_str(&format!("#~ msgstr[{index}] {}\n", quoted(form)));
                }
            }
            out.push('\n');
        }
    }

    if let Err(e) = fs::write(path, out) {
        eprintln!("error: could not write {}: {e}", path.display());
        return;
    }
    let name = path.file_name().unwrap_or_default().to_string_lossy();
    if is_template {
        println!("Wrote {name} ({} messages).", messages.len());
    } else {
        let bad = check_placeholders(path);
        println!(
            "Wrote {name}: {translated}/{} translated, {} obsolete kept{}.",
            messages.len(),
            existing.len(),
            if bad == 0 {
                String::new()
            } else {
                format!(", {bad} WITH PLACEHOLDER PROBLEMS")
            }
        );
    }
}

/// Reports translations whose placeholders do not match their msgid's.
///
/// A dropped `{name}` is the one translation mistake that cannot be seen by
/// reading the Spanish: the sentence still makes sense, and the value it was
/// supposed to carry — a device, a file, a URL — simply never appears. An added
/// one is as bad the other way, since `i18n::interpolate` leaves an unknown name
/// standing and the user reads the braces. Both are cheap to find here and
/// expensive to notice in a running app, so `gen-po` looks every time.
fn check_placeholders(path: &Path) -> usize {
    /// The names in `{...}`, ignoring `{{` and `}}` escapes.
    fn names(text: &str) -> std::collections::BTreeSet<String> {
        let mut out = std::collections::BTreeSet::new();
        let chars: Vec<char> = text.chars().collect();
        let mut i = 0;
        while i < chars.len() {
            if chars[i] != '{' {
                i += 1;
                continue;
            }
            if chars.get(i + 1) == Some(&'{') {
                i += 2;
                continue;
            }
            let start = i + 1;
            let mut j = start;
            while j < chars.len() && chars[j] != '}' {
                j += 1;
            }
            let name: String = chars[start..j.min(chars.len())].iter().collect();
            if !name.is_empty()
                && name.chars().all(|c| c.is_alphanumeric() || c == '_')
                && !name.chars().next().is_some_and(|c| c.is_ascii_digit())
            {
                out.insert(name);
            }
            i = j + 1;
        }
        out
    }

    let Ok(text) = fs::read_to_string(path) else {
        return 0;
    };
    let mut problems = 0;
    for entry in i18n::parse_po(&text) {
        if entry.id.is_empty() {
            continue;
        }
        let mut wanted = names(&entry.id);
        if let Some(plural) = &entry.id_plural {
            wanted.extend(names(plural));
        }
        for form in entry.msgstrs.iter().filter(|s| !s.is_empty()) {
            let got = names(form);
            if got != wanted {
                problems += 1;
                eprintln!(
                    "warning: placeholders differ for {:?}\n  msgid wants {:?}, translation has {:?}",
                    truncate(&entry.id),
                    wanted,
                    got
                );
            }
        }
    }
    problems
}

fn truncate(text: &str) -> String {
    if text.chars().count() <= 60 {
        return text.to_string();
    }
    text.chars().take(57).collect::<String>() + "..."
}

/// Renders a string as one or more `.po` quoted lines.
///
/// Long messages — every context-help paragraph — are wrapped, because a `.po`
/// with 400-character lines is unreadable in the editors translators actually
/// use. The parser joins the pieces back with no separator, so wrapping is free
/// as long as the break lands after an existing space.
fn quoted(text: &str) -> String {
    const WRAP: usize = 72;
    if text.len() <= WRAP && !text.contains('\n') {
        return format!("\"{}\"", po_escape(text));
    }
    let mut lines: Vec<String> = Vec::new();
    let mut current = String::new();
    for word in split_keeping_spaces(text) {
        if !current.is_empty() && current.len() + word.len() > WRAP {
            lines.push(std::mem::take(&mut current));
        }
        current.push_str(&word);
        // A hard newline inside the text is a natural break point.
        if word.ends_with('\n') {
            lines.push(std::mem::take(&mut current));
        }
    }
    if !current.is_empty() {
        lines.push(current);
    }
    let mut out = String::from("\"\"\n");
    for line in lines {
        out.push_str(&format!("\"{}\"\n", po_escape(&line)));
    }
    // Drop the trailing newline; the caller adds one.
    out.pop();
    out
}

/// Splits into words, keeping each word's trailing whitespace attached so
/// rejoining the pieces reproduces the original exactly.
fn split_keeping_spaces(text: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut current = String::new();
    let mut in_space = false;
    for c in text.chars() {
        if c.is_whitespace() {
            in_space = true;
            current.push(c);
        } else {
            if in_space {
                out.push(std::mem::take(&mut current));
                in_space = false;
            }
            current.push(c);
        }
    }
    if !current.is_empty() {
        out.push(current);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_scanner_reads_both_macros() {
        let source = r#"
            let a = t!("Output device");
            let b = tn!("{n} listener", "{n} listeners", count);
            let c = t!("Streaming at {rate} kbps", rate = 128);
        "#;
        let calls = scan_calls(source);
        assert_eq!(calls.len(), 3);
        assert_eq!(calls[0].singular, "Output device");
        assert_eq!(calls[1].singular, "{n} listener");
        assert_eq!(calls[1].plural.as_deref(), Some("{n} listeners"));
        assert_eq!(calls[2].singular, "Streaming at {rate} kbps");
    }

    #[test]
    fn the_scanner_joins_a_backslash_continued_literal() {
        // How every long message in the UI is actually written. Getting this
        // wrong produces a msgid with a newline and a run of spaces in it,
        // which no translation would ever match at runtime.
        let source = "let x = t!(\"one two \\\n             three\");";
        let calls = scan_calls(source);
        assert_eq!(calls.len(), 1);
        assert_eq!(calls[0].singular, "one two three");
    }

    #[test]
    fn a_continuation_is_joined_over_crlf_too() {
        // Every file in this repository is CRLF, so this is not the edge case
        // it looks like — it is the normal path. rustc normalises the line
        // ending before lexing; so must this.
        let source = "let x = t!(\"one two \\\r\n             three\");";
        let calls = scan_calls(source);
        assert_eq!(calls.len(), 1);
        assert_eq!(calls[0].singular, "one two three");
    }

    #[test]
    fn the_scanner_ignores_comments_strings_and_lookalike_identifiers() {
        let source = r####"
            // t!("in a line comment")
            /* t!("in a block comment") */
            let s = "t!(\"inside a string\")";
            let r = r#"t!("inside a raw string")"#;
            assert!(x);            // `assert!` must not read as `t!`
            let real = t!("only me");
        "####;
        let calls = scan_calls(source);
        assert_eq!(
            calls
                .iter()
                .map(|c| c.singular.as_str())
                .collect::<Vec<_>>(),
            vec!["only me"]
        );
    }

    #[test]
    fn line_numbers_point_at_the_call() {
        let source = "fn a() {}\n\nlet x = t!(\"here\");\n";
        let calls = scan_calls(source);
        assert_eq!(calls[0].line, 3);
    }

    #[test]
    fn wrapped_output_round_trips_through_the_parser() {
        // The property the whole file depends on: what `quoted` writes, the
        // runtime's own parser must read back byte for byte.
        let long = "This is a deliberately long context-help paragraph, of the sort \
                    help.toml is full of, which the writer will wrap across several \
                    lines and which must come back out of the parser exactly as it \
                    went in -- including its \"quotes\" and its punctuation.";
        let po = format!(
            "msgid \"\"\nmsgstr \"\"\n\nmsgid {}\nmsgstr \"\"\n",
            quoted(long)
        );
        let entries = i18n::parse_po(&po);
        let entry = entries
            .iter()
            .find(|e| !e.id.is_empty())
            .expect("the wrapped entry parses");
        assert_eq!(entry.id, long);
    }

    #[test]
    fn a_multi_line_message_round_trips_too() {
        let text = "First line.\nSecond line.\n\nAfter a blank.";
        let po = format!(
            "msgid \"\"\nmsgstr \"\"\n\nmsgid {}\nmsgstr \"\"\n",
            quoted(text)
        );
        let entry = i18n::parse_po(&po)
            .into_iter()
            .find(|e| !e.id.is_empty())
            .expect("parses");
        assert_eq!(entry.id, text);
    }
}
